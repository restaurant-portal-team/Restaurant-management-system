/**
 * npm run unicode:generate
 *
 * Regenerates src/common/unicode/pg-simple-lower.generated.ts from the PostgreSQL 17 builtin-provider
 * case table (default: C:/Program Files/PostgreSQL/17/include/server/common, override with
 * PG_COMMON_INCLUDE_DIR). Offline; no database connection. Re-run (and re-verify) whenever the target
 * PostgreSQL major version changes.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { BACKEND_ROOT } from '../db/migration-env.ts';
import { readPgCaseTable } from './pg-case-table.ts';

const OUTPUT = resolve(BACKEND_ROOT, 'src', 'common', 'unicode', 'pg-simple-lower.generated.ts');

const table = readPgCaseTable();
const hex = (n: number): string => `0x${n.toString(16)}`;

const lines: string[] = [];
for (let i = 0; i < table.changing.length; i += 6) {
  const chunk = table.changing.slice(i, i + 6).map(([cp, lower]) => `${hex(cp)}, ${hex(lower)}`);
  lines.push(`  ${chunk.join(', ')},`);
}

const content = `// AUTO-GENERATED by scripts/unicode/generate-pg-simple-lower.ts — DO NOT EDIT.
// Source: PostgreSQL 17 builtin provider unicode_case_table.h (CaseLower simple mappings).
// This is the exact mapping used by lower(text COLLATE "pg_c_utf8") in PostgreSQL 17.

/** Unicode version of the PostgreSQL case table this mapping was generated from. */
export const PG_UNICODE_VERSION = '${table.unicodeVersion}';

/** Number of codepoints whose simple lowercase differs from the codepoint itself. */
export const PG_SIMPLE_LOWER_COUNT = ${table.changing.length};

/** Flat list of [codepoint, simpleLowercase] pairs, sorted by codepoint. */
export const PG_SIMPLE_LOWER_PAIRS: readonly number[] = [
${lines.join('\n')}
];
`;

writeFileSync(OUTPUT, content, { encoding: 'utf8' });
console.log(
  `[unicode:generate] wrote ${table.changing.length} mappings (Unicode ${table.unicodeVersion}) to src/common/unicode/pg-simple-lower.generated.ts`,
);
